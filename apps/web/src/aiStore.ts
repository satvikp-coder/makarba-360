import { useEffect, useState } from "react";
import { ICON_NAMES, type IconName } from "./Icon.js";
import { fmt, signals, type ForecastDoc, type Signal } from "./outlook.js";
import { ANCHORS } from "./scenario.js";

/**
 * AI insights, generated in the background and cached.
 *
 * - Highlights are GENERATIVE UI: the model returns structured items (title, body, icon, tone, map anchor, indicator ids) and the app
 *   renders them as cards and map callouts. Icons and anchors must come from fixed lists, and every number shown next to a highlight is
 *   read from the forecast file, never from the model's text.
 * - The briefing is free text, streamed.
 * - Both run once per (forecast file, end year, provider, model) and are cached in localStorage, so revisits are instant.
 * - Output is always labelled as AI-generated by the components that show it.
 */

export type Provider = "applefm" | "ollama" | "groq";
export type Tone = "positive" | "negative" | "mixed";
export interface Highlight { id: string; title: string; body: string; icon: IconName; tone: Tone; anchor: keyof typeof ANCHORS; indicators: string[] }
export interface AiEntry {
  status: "idle" | "running" | "done" | "error" | "offline";
  phase?: "highlights" | "briefing";
  headline?: string;
  highlights?: Highlight[];
  briefing?: string;
  provider?: Provider;
  model?: string;
  at?: string;
  error?: string;
}

const PREF_KEY = "makarba.ai.choice.v1";
const CACHE_PREFIX = "makarba.ai.v2:";
const HIGHLIGHT_ICONS: IconName[] = ["building", "home2", "car", "bus", "thermo", "drop", "leaf", "bolt", "users", "coins", "shield", "heart", "wifi", "school", "factory", "haze", "shop", "landmark", "water", "trend", "chart"];

export const PROVIDERS: Record<Provider, { label: string; note: string; list: string; models: (d: unknown) => string[] }> = {
  applefm: { label: "Apple Intelligence", note: "Apple's on-device Foundation Model; nothing leaves this Mac.", list: "/applefm/health",
    models: (d) => ((d as { available?: boolean }).available ? ["apple-foundation-model"] : []) },
  ollama: { label: "On-device (Ollama)", note: "Runs on this computer; nothing leaves it.", list: "/ollama/api/tags",
    models: (d) => ((d as { models?: { name: string }[] }).models ?? []).map((m) => m.name) },
  groq: { label: "Groq (cloud)", note: "Sends the forecast numbers (no personal data) to Groq's servers.", list: "/groq/models",
    models: (d) => ((d as { data?: { id: string }[] }).data ?? []).map((m) => m.id).filter((id) => !/whisper|tts|guard|embed|orpheus|playai/i.test(id)).sort() },
};

export function getChoice(): { provider: Provider; model: string } | null {
  try { return JSON.parse(localStorage.getItem(PREF_KEY) ?? "null"); } catch { return null; }
}
export function setChoice(c: { provider: Provider; model: string }) {
  try { localStorage.setItem(PREF_KEY, JSON.stringify(c)); } catch { /* ignore */ }
}

export async function listModels(p: Provider): Promise<string[]> {
  try {
    const r = await fetch(PROVIDERS[p].list);
    return r.ok ? PROVIDERS[p].models(await r.json()) : [];
  } catch { return []; }
}
const preferred = (models: string[]) => models.find((m) => /gemma|llama-3\.3-70b|gpt-oss-120b|qwen/i.test(m)) ?? models[0] ?? "";

/**
 * First available provider, in the visitor's saved order, else on-device first. Background (unasked) runs never use the cloud
 * unless the visitor chose Groq themselves before: forecast numbers are only sent off the device on request.
 */
export async function pickProvider(background = false): Promise<{ provider: Provider; model: string } | null> {
  const saved = getChoice();
  // Apple's on-device model first whenever it is available, then Ollama; the visitor's saved choice wins.
  const order: Provider[] = ["applefm", "ollama", "groq"];
  if (saved) order.sort((a, b) => (a === saved.provider ? -1 : b === saved.provider ? 1 : 0));
  if (background && saved?.provider !== "groq") order.splice(order.indexOf("groq"), 1);
  for (const p of order) {
    const models = await listModels(p);
    if (models.length) return { provider: p, model: saved?.provider === p && models.includes(saved.model) ? saved.model : preferred(models) };
  }
  return null;
}

// --- store ------------------------------------------------------------------------------------------------------------------
const entries = new Map<string, AiEntry>();
const subs = new Set<() => void>();
const notify = () => subs.forEach((f) => f());
const keyOf = (doc: ForecastDoc, year: number) => `${doc.generated}:${doc.series.length}:${year}`;

function readCache(k: string): AiEntry | null {
  try { const v = JSON.parse(localStorage.getItem(CACHE_PREFIX + k) ?? "null") as AiEntry | null; return v?.status === "done" ? v : null; } catch { return null; }
}
function writeCache(k: string, e: AiEntry) {
  try { localStorage.setItem(CACHE_PREFIX + k, JSON.stringify(e)); } catch { /* quota: keep in memory only */ }
}
function put(k: string, e: AiEntry) { entries.set(k, e); notify(); }

export function getAi(doc: ForecastDoc | null, year: number): AiEntry {
  if (!doc) return { status: "idle" };
  const k = keyOf(doc, year);
  return entries.get(k) ?? readCache(k) ?? { status: "idle" };
}

export function useAi(doc: ForecastDoc | null, year: number): AiEntry {
  const [, tick] = useState(0);
  useEffect(() => { const f = () => tick((n) => n + 1); subs.add(f); return () => { subs.delete(f); }; }, []);
  return getAi(doc, year);
}

/** Any generation in progress anywhere (drives the thinking orb in the shell). */
export function useAiBusy(): boolean {
  const [, tick] = useState(0);
  useEffect(() => { const f = () => tick((n) => n + 1); subs.add(f); return () => { subs.delete(f); }; }, []);
  return [...entries.values()].some((e) => e.status === "running");
}

// --- prompts ----------------------------------------------------------------------------------------------------------------
/** Apple's on-device model has a small context window: give it the strongest signals only. */
export const forProvider = (sig: Signal[], p: Provider) => (p === "applefm" ? [...sig].sort((a, b) => Math.abs(b.pct ?? b.change * 50) - Math.abs(a.pct ?? a.change * 50)).slice(0, 28) : sig);
const lines = (sig: Signal[]) => sig.map((x) => `- ${x.s.id} | ${x.s.label} (${x.s.theme}): ${fmt(x.from.value)} in ${Math.floor(x.from.year)} -> ${fmt(x.to.value)} in ${Math.floor(x.to.year)} ${x.s.unit}; ${x.verdict}, ${x.momentum}, confidence ${x.confidence}`).join("\n");
const CONTEXT = (year: number) => `Makarba is a fast-growing peri-urban ward on the south-west edge of Ahmedabad, Gujarat, India, beside the Sarkhej–Gandhinagar Highway, the 15th-century Sarkhej Roza complex and its lake, and a canal. The data below are Google TimesFM forecasts to ${year}: mostly national India series; series starting KAGGLE_AHD or WEATHER_AHD are Ahmedabad city air quality and weather. None are Makarba measurements.`;

export function highlightsPrompt(sig: Signal[], year: number): string {
  const anchors = Object.entries(ANCHORS).map(([k, a]) => `${k} (${a.label})`).join(", ");
  return `${CONTEXT(year)}

Pick the 4 to 6 MOST IMPORTANT and DIFFERENT things these forecasts could mean for daily life in Makarba by ${year}. Mix themes (housing, mobility, heat, air, jobs, services, governance). Prefer strong, confident signals.
Return JSON only, exactly: {"headline": string (max 90 chars), "highlights": [{"title": string (max 40 chars), "body": string (max 160 chars, plain words, use "could"/"may", NO digits), "icon": one of [${HIGHLIGHT_ICONS.join(", ")}], "tone": "positive"|"negative"|"mixed", "anchor": one of [${Object.keys(ANCHORS).join(", ")}], "indicators": [1-3 series ids from the list]}]}
Anchors are places on the 3D map: ${anchors}. Choose the anchor where the effect would be most visible.

Forecasts:
${lines(sig)}`;
}

export function briefingPrompt(sig: Signal[], year: number): string {
  return `You are an urban-planning analyst. ${CONTEXT(year)}
Write a short briefing in plain English (max 230 words) with these headings:
**Big picture**, **What it could mean for Makarba** (4 bullet points: housing, mobility, heat and air, services and jobs), **Risks to watch** (2 bullets).
Use only the numbers given. Say "could" or "may", never "will". Mention once that these are national and city trends, not local measurements.

${lines(sig)}`;
}

// --- transport --------------------------------------------------------------------------------------------------------------
async function call(provider: Provider, model: string, prompt: string, opts: { json: boolean; signal?: AbortSignal; onText?: (t: string) => void }): Promise<string> {
  const stream = !!opts.onText;
  const r = provider === "applefm"
    ? await fetch("/applefm/generate", { method: "POST", signal: opts.signal, headers: { "Content-Type": "application/json" }, body: JSON.stringify({ prompt, stream, json: opts.json }) })
    : provider === "ollama"
    ? await fetch("/ollama/api/generate", { method: "POST", signal: opts.signal, headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ model, prompt, stream, ...(opts.json ? { format: "json" } : {}), options: { temperature: opts.json ? 0.2 : 0.3 } }) })
    : await fetch("/groq/chat/completions", { method: "POST", signal: opts.signal, headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ model, stream, temperature: opts.json ? 0.2 : 0.3, ...(opts.json ? { response_format: { type: "json_object" } } : {}), messages: [{ role: "user", content: prompt }] }) });
  if (!r.ok) throw new Error(`HTTP ${r.status}`);
  if (!stream) {
    const j = await r.json() as { response?: string; choices?: { message?: { content?: string } }[] };
    return (provider === "groq" ? j.choices?.[0]?.message?.content : j.response) ?? "";
  }
  if (!r.body) throw new Error("no body");
  const reader = r.body.getReader(); const dec = new TextDecoder(); let buf = "", all = "";
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    buf += dec.decode(value, { stream: true });
    const ls = buf.split("\n"); buf = ls.pop() ?? "";
    for (const raw of ls) {
      const l = provider === "groq" ? raw.replace(/^data:\s*/, "").trim() : raw.trim();
      if (!l || l === "[DONE]") continue;
      const j = JSON.parse(l) as { response?: string; replace?: boolean; choices?: { delta?: { content?: string } }[] };
      const t = provider === "groq" ? j.choices?.[0]?.delta?.content : j.response;
      if (t) { all = j.replace ? t : all + t; opts.onText?.(all); }
    }
  }
  return all;
}

/** Validates and cleans the model's highlights; anything outside the fixed lists is dropped, so the UI can trust every field. */
export function parseHighlights(raw: string, validIds: Set<string>): { headline: string; highlights: Highlight[] } | null {
  let j: unknown;
  try { j = JSON.parse(raw.slice(raw.indexOf("{"), raw.lastIndexOf("}") + 1)); } catch { return null; }
  const o = j as { headline?: unknown; highlights?: unknown };
  if (!Array.isArray(o.highlights)) return null;
  const clip = (v: unknown, n: number) => (typeof v === "string" ? v.replace(/\s+/g, " ").trim().slice(0, n) : "");
  const seen = new Set<string>();
  const list: Highlight[] = [];
  for (const h of o.highlights as Record<string, unknown>[]) {
    const anchor = String(h["anchor"] ?? "") as keyof typeof ANCHORS;
    const icon = String(h["icon"] ?? "") as IconName;
    const title = clip(h["title"], 48), body = clip(h["body"], 200)
      .replace(/\s*\b(by|in|until|to|from|around|after|before)\s+(the\s+year\s+)?\d{4}\b/gi, "")   // whole year phrases, not a dangling "by"
      .replace(/\d[\d,.]*\s*%?/g, "").replace(/\s{2,}/g, " ").replace(/\s+([,.;])/g, "$1").trim();
    if (!title || !body || !(anchor in ANCHORS)) continue;
    const key = `${anchor}:${title.toLowerCase()}`;
    if (seen.has(key)) continue;
    seen.add(key);
    list.push({
      id: `h${list.length + 1}`, title, body,
      icon: ICON_NAMES.includes(icon) ? icon : "spark",
      tone: h["tone"] === "positive" || h["tone"] === "negative" ? h["tone"] : "mixed",
      anchor,
      indicators: (Array.isArray(h["indicators"]) ? h["indicators"] : []).map(String).filter((id) => validIds.has(id)).slice(0, 3),
    });
    if (list.length === 6) break;
  }
  return list.length >= 2 ? { headline: clip(o.headline, 110), highlights: list } : null;
}

// --- orchestration ----------------------------------------------------------------------------------------------------------
const running = new Map<string, Promise<void>>();

/**
 * Makes sure highlights and a briefing exist for this year. Cached results return at once; concurrent calls share one run.
 * `force` regenerates; `choice` overrides the provider/model (and is remembered).
 */
export function ensureAi(doc: ForecastDoc, year: number, opts: { force?: boolean; background?: boolean; choice?: { provider: Provider; model: string } } = {}): Promise<void> {
  const k = keyOf(doc, year);
  if (!opts.force && (entries.get(k)?.status === "done" || readCache(k))) { if (!entries.has(k)) entries.set(k, readCache(k)!); return Promise.resolve(); }
  if (running.has(k) && !opts.force) return running.get(k)!;
  const job = (async () => {
    const choice = opts.choice ?? await pickProvider(opts.background);
    if (!choice) { put(k, { status: "offline" }); return; }
    if (opts.choice) setChoice(opts.choice);
    const sig = forProvider(signals(doc, year), choice.provider);
    const ids = new Set(sig.map((x) => x.s.id));
    const base: AiEntry = { status: "running", phase: "highlights", provider: choice.provider, model: choice.model };
    put(k, base);
    try {
      let parsed = parseHighlights(await call(choice.provider, choice.model, highlightsPrompt(sig, year), { json: true }), ids);
      if (!parsed) parsed = parseHighlights(await call(choice.provider, choice.model, highlightsPrompt(sig, year), { json: true }), ids); // one retry
      const withH: AiEntry = { ...base, phase: "briefing", headline: parsed?.headline, highlights: parsed?.highlights };
      put(k, withH);
      const briefing = await call(choice.provider, choice.model, briefingPrompt(sig, year), { json: false, onText: (t) => put(k, { ...withH, briefing: t }) });
      const done: AiEntry = { ...withH, status: "done", phase: undefined, briefing, at: new Date().toISOString() };
      put(k, done);
      writeCache(k, done);
    } catch (e) {
      put(k, { ...base, status: "error", error: e instanceof Error ? e.message : String(e) });
    }
  })().finally(() => running.delete(k));
  running.set(k, job);
  return job;
}
