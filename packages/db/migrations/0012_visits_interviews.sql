-- 0012 (additive): field visits, interviews (client UUID, idempotent start) and draft answers (issues #44, #45, part of #47).
-- Interviews pin ONE published questionnaire version and need a granted participation consent first. Answers are draft-only and are
-- DISCARDED, together with everything the participant said, when participation is refused or withdrawn (the interview row stays as a
-- bare "withdrawn" marker). Genuine interviews are never deleted by the API (#59).
-- No participant data may be entered before ethics approval (#11); everything here is exercised with synthetic data.

CREATE TABLE private.field_visits (
  id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  study_area_id uuid        NOT NULL,
  researcher_id uuid        NOT NULL REFERENCES private.users (id),
  status        text        NOT NULL DEFAULT 'active' CHECK (status IN ('active','ended','cancelled')),
  started_at    timestamptz NOT NULL DEFAULT now(),
  ended_at      timestamptz,
  CONSTRAINT visit_end_matches_status CHECK ((status = 'active') = (ended_at IS NULL))
);
CREATE INDEX field_visits_researcher ON private.field_visits (researcher_id, status);
CREATE INDEX field_visits_study ON private.field_visits (study_area_id);

CREATE TABLE audit.field_visit_status_history (
  id        bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  visit_id  uuid        NOT NULL,
  status    text        NOT NULL,
  at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX field_visit_history_visit ON audit.field_visit_status_history (visit_id, id);

CREATE FUNCTION private.guard_field_visit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'visits are never deleted' USING ERRCODE = '23001'; END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'active' THEN RAISE EXCEPTION 'a visit starts active' USING ERRCODE = '23001'; END IF;
    INSERT INTO audit.field_visit_status_history (visit_id, status) VALUES (NEW.id, NEW.status);
    RETURN NEW;
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.study_area_id IS DISTINCT FROM OLD.study_area_id
     OR NEW.researcher_id IS DISTINCT FROM OLD.researcher_id OR NEW.started_at IS DISTINCT FROM OLD.started_at THEN
    RAISE EXCEPTION 'visit identity is fixed' USING ERRCODE = '23001';
  END IF;
  IF OLD.status <> 'active' THEN RAISE EXCEPTION 'an ended or cancelled visit is frozen' USING ERRCODE = '23001'; END IF;
  IF NEW.status <> OLD.status THEN INSERT INTO audit.field_visit_status_history (visit_id, status) VALUES (NEW.id, NEW.status); END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER field_visits_guard BEFORE INSERT OR UPDATE OR DELETE ON private.field_visits
  FOR EACH ROW EXECUTE FUNCTION private.guard_field_visit();

CREATE TABLE private.interviews (
  id                uuid        PRIMARY KEY,                     -- generated by the client once, so a repeated tap or retry is the same interview
  visit_id          uuid        NOT NULL REFERENCES private.field_visits (id),
  study_area_id     uuid        NOT NULL,
  collector_id      uuid        NOT NULL REFERENCES private.users (id),
  survey_version_id uuid        NOT NULL REFERENCES private.survey_versions (id),
  status            text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','abandoned','withdrawn')),
  started_at        timestamptz NOT NULL,                        -- device time as reported
  started_offset_minutes integer NOT NULL CHECK (started_offset_minutes BETWEEN -840 AND 840),
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX interviews_visit ON private.interviews (visit_id, status);
CREATE INDEX interviews_collector ON private.interviews (collector_id);
CREATE INDEX interviews_survey_version ON private.interviews (survey_version_id);
CREATE INDEX interviews_study ON private.interviews (study_area_id);

CREATE TABLE private.interview_answers (
  interview_id   uuid        NOT NULL REFERENCES private.interviews (id),
  question_code  text        NOT NULL CHECK (question_code ~ '^[A-Z][A-Z0-9_]{1,23}$'),
  value          jsonb,
  missing_reason text        CHECK (missing_reason IN ('skipped','refused','unsure','not_applicable')),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (interview_id, question_code),
  CONSTRAINT answer_is_value_xor_missing CHECK ((value IS NULL) <> (missing_reason IS NULL))
);

CREATE FUNCTION private.guard_interview() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v private.field_visits%ROWTYPE;
  sv_status text;
  consent text;
  consent_owner uuid;
  consent_study uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'interviews are never deleted' USING ERRCODE = '23001'; END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT * INTO v FROM private.field_visits WHERE id = NEW.visit_id;
    IF v.status IS DISTINCT FROM 'active' THEN RAISE EXCEPTION 'the visit is not active' USING ERRCODE = '23001'; END IF;
    IF v.researcher_id <> NEW.collector_id OR v.study_area_id <> NEW.study_area_id THEN
      RAISE EXCEPTION 'interview must belong to the visit researcher and study' USING ERRCODE = '23001';
    END IF;
    SELECT status INTO sv_status FROM private.survey_versions WHERE id = NEW.survey_version_id;
    IF sv_status IS DISTINCT FROM 'published' THEN RAISE EXCEPTION 'questionnaire version is not published' USING ERRCODE = '23001'; END IF;
    IF NEW.status <> 'draft' THEN RAISE EXCEPTION 'an interview starts as a draft' USING ERRCODE = '23001'; END IF;
    SELECT decision, recorded_by, study_area_id INTO consent, consent_owner, consent_study
      FROM private.consent_events WHERE interview_id = NEW.id AND scope = 'participation' ORDER BY id DESC LIMIT 1;
    IF consent IS DISTINCT FROM 'granted' OR consent_owner <> NEW.collector_id OR consent_study <> NEW.study_area_id THEN
      RAISE EXCEPTION 'participation consent must be granted before the interview starts' USING ERRCODE = '23001';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.visit_id IS DISTINCT FROM OLD.visit_id OR NEW.study_area_id IS DISTINCT FROM OLD.study_area_id
     OR NEW.collector_id IS DISTINCT FROM OLD.collector_id OR NEW.survey_version_id IS DISTINCT FROM OLD.survey_version_id
     OR NEW.started_at IS DISTINCT FROM OLD.started_at OR NEW.started_offset_minutes IS DISTINCT FROM OLD.started_offset_minutes THEN
    RAISE EXCEPTION 'interview identity is fixed' USING ERRCODE = '23001';
  END IF;
  IF NEW.status <> OLD.status THEN
    IF OLD.status = 'withdrawn' THEN RAISE EXCEPTION 'a withdrawn interview is final' USING ERRCODE = '23001'; END IF;
    IF NEW.status = 'withdrawn' THEN RETURN NEW; END IF;                         -- set by the consent trigger
    IF NOT (OLD.status = 'draft' AND NEW.status IN ('submitted','abandoned')) THEN RAISE EXCEPTION 'invalid interview status change' USING ERRCODE = '23001'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER interviews_guard BEFORE INSERT OR UPDATE OR DELETE ON private.interviews
  FOR EACH ROW EXECUTE FUNCTION private.guard_interview();

CREATE FUNCTION private.guard_interview_answer() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE i private.interviews%ROWTYPE; instr jsonb;
BEGIN
  IF TG_OP = 'DELETE' THEN
    -- Only the consent-loss discard (which sets this transaction-local flag; the API role has no DELETE grant anyway) may remove answers.
    IF coalesce(current_setting('makarba.discarding', true), '') = 'on' THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'answers are not deleted; withdrawal discards them' USING ERRCODE = '23001';
  END IF;
  SELECT * INTO i FROM private.interviews WHERE id = NEW.interview_id;
  IF i.status IS DISTINCT FROM 'draft' THEN RAISE EXCEPTION 'answers can only change while the interview is a draft' USING ERRCODE = '23001'; END IF;
  IF TG_OP = 'UPDATE' AND (NEW.interview_id <> OLD.interview_id OR NEW.question_code <> OLD.question_code) THEN
    RAISE EXCEPTION 'answer identity is fixed' USING ERRCODE = '23001';
  END IF;
  SELECT instrument INTO instr FROM private.survey_versions WHERE id = i.survey_version_id;
  IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(instr -> 'questions') q WHERE q ->> 'code' = NEW.question_code) THEN
    RAISE EXCEPTION 'question % is not in the pinned questionnaire version', NEW.question_code USING ERRCODE = '23001';
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END $$;
CREATE TRIGGER interview_answers_guard BEFORE INSERT OR UPDATE OR DELETE ON private.interview_answers
  FOR EACH ROW EXECUTE FUNCTION private.guard_interview_answer();

-- Refusal or withdrawal of participation discards everything the participant said and marks the interview withdrawn.
-- SECURITY DEFINER because the API role (rightly) has no DELETE; the function does nothing else.
CREATE FUNCTION private.discard_on_consent_loss() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = private, pg_temp AS $$
BEGIN
  IF NEW.scope = 'participation' AND NEW.decision IN ('refused','withdrawn') THEN
    PERFORM set_config('makarba.discarding', 'on', true);
    DELETE FROM private.interview_answers WHERE interview_id = NEW.interview_id;
    PERFORM set_config('makarba.discarding', 'off', true);
    UPDATE private.interviews SET status = 'withdrawn' WHERE id = NEW.interview_id AND status <> 'withdrawn';
  END IF;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION private.discard_on_consent_loss() FROM PUBLIC;
CREATE TRIGGER consent_events_discard AFTER INSERT ON private.consent_events
  FOR EACH ROW EXECUTE FUNCTION private.discard_on_consent_loss();

REVOKE DELETE ON private.field_visits, private.interviews, private.interview_answers FROM makarba_private_api;
GRANT SELECT ON audit.field_visit_status_history TO makarba_private_api;
